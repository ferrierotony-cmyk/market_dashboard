"""Page head helpers: titles, the head of a case page and the focal point classes for photos.
All styling lives in styles/tokens.css and styles/site.css. Nothing here writes a style attribute."""
import html as _html
import re as _re


def _e(s):
    return _html.escape(s, quote=True)


def split(text, dot=True):
    """A page title. The clay dot rides the last word."""
    return _e(text) + ("<i>.</i>" if dot else "")


# Focal points: where a cropped photo should stay anchored. Each distinct value becomes one class,
# and the build writes the matching rules into style.css.
FOCAL = {}


def fp(pos):
    """Class name for an object position such as 'center 68%'. Registers the rule for the stylesheet."""
    pos = " ".join(pos.split())
    if pos in ("center", "center center", "50% 50%"):
        return ""
    name = "fp-" + _re.sub(r"[^a-z0-9]+", "-", pos.lower()).strip("-")
    FOCAL[name] = pos
    return name


def focal_css():
    rules = "".join(".%s { object-position: %s; }\n" % (k, v) for k, v in sorted(FOCAL.items()))
    return "\n/* ---------- photo focal points, generated by the build ---------- */\n" + rules


# Pictures that travel from a tile to their page. Each gets one class, and the build writes the matching rules.
VT = set()


def vt(fname):
    """Short name for a case file, shared by its tile and its page."""
    name = fname.replace(".html", "")
    VT.add(name)
    return name


def vt_css():
    rules = "".join(".vt-%s { view-transition-name: fig-%s; view-transition-class: figure; }\n" % (n, n) for n in sorted(VT))
    return "\n/* ---------- travelling pictures, generated by the build ---------- */\n" + rules


def _cls(name):
    return ' class="%s"' % name if name else ""


AI_DIR = None  # set by the build: folder that may hold assets/ai/<slug>.jpg


def ai_image(img_src):
    """Path of an AI generated image for this page, if one was dropped into assets/ai. Slug comes from the old banner name."""
    import os
    if not AI_DIR:
        return None
    slug = os.path.basename(img_src).replace(".jpg", "").replace("d-", "", 1).replace("-m", "")
    rel = "assets/ai/%s.jpg" % slug
    return rel if os.path.exists(os.path.join(AI_DIR, rel)) else None


def page_head(crumb_html, h1, meta, lede, img_src=None, cap="", pos="center 30%", travel=""):
    """Case page head on the centre axis: way back, title, one line of context, a chart or real photo, then the lede.
    The drawn banners are retired. An AI generated image shows only if one exists, and says so in its caption."""
    fig = ""
    if img_src and "/d-" in img_src:
        ai = ai_image(img_src)
        if ai:
            fig = (f'<figure class="page-fig"><img src="{ai}" alt="" fetchpriority="high"{_cls(fp(pos))}>'
                   f'<figcaption>AI generated image, not a photo of the real place.</figcaption></figure>')
    elif img_src:
        cls = " ".join(x for x in (fp(pos), "vt-" + travel if travel else "") if x)
        shape = "page-fig photo" if "/photos/" in img_src else "page-fig"
        fig = (f'<figure class="{shape}"><img src="{img_src}" alt="{_e(cap) if "/photos/" in img_src else ""}" fetchpriority="high"{_cls(cls)}>'
               f'<figcaption>{_e(cap)}</figcaption></figure>')
    return (f'<header class="page-head"><div class="wrap">{crumb_html}<h1>{split(h1)}</h1>'
            f'<p class="meta">{_e(meta)}</p>{fig}<p class="lede">{_e(lede)}</p></div></header>')
